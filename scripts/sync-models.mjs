#!/usr/bin/env node
/**
 * Sync the model catalogue from APIsRouter's public /v1/models endpoint.
 *
 * Output: packages/shared/src/generated/apisrouterModels.ts
 *
 * The endpoint is public and already includes live per-1M-token pricing, so
 * this script is the source of truth for:
 *   - the model picker (LLM_MODEL_OPTIONS.apisrouter)
 *   - the free-tier allow-list (cheapest chat-capable models)
 *   - cost estimates
 *
 * Run manually: pnpm models:sync
 * It is deliberately NOT part of the build, so builds never depend on network.
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'packages/shared/src/generated/apisrouterModels.ts')
const ENDPOINT = process.env.MODELS_ENDPOINT || 'https://apisrouter.dev/v1/models'

/** Models shown first in the picker (order preserved). */
const FEATURED = [
  'claude-sonnet-5.5',
  'claude-opus-5.5',
  'gpt-6.1-sol-pro',
  'gemini-4-argon',
  'kimi-k2.7-code',
  'deepseek-v4.1-flash',
  'grok-4.7',
  'qwen3.8-max-prime',
]

/** A model is "cheap" when one typical chat turn stays well under a cent. */
const CHEAP_MAX_INPUT_PER_1M = 0.35
const CHEAP_MAX_OUTPUT_PER_1M = 1.6

const res = await fetch(ENDPOINT, { headers: { accept: 'application/json' } })
if (!res.ok) {
  console.error(`[models] ${ENDPOINT} -> ${res.status} ${res.statusText}`)
  process.exit(1)
}

const payload = await res.json()
const raw = Array.isArray(payload?.data) ? payload.data : []
if (raw.length === 0) {
  console.error('[models] API returned no models; refusing to overwrite the catalogue')
  process.exit(1)
}

const num = (value) => {
  const n = Number(value)
  return Number.isFinite(n) ? n : null
}

const models = raw
  .map((m) => ({
    id: String(m.id || '').trim(),
    name: String(m.name || m.id || '').trim(),
    provider: String(m.owned_by || 'unknown').trim(),
    contextLength: num(m.context_length),
    maxCompletionTokens: num(m.max_completion_tokens),
    inputPer1M: num(m.pricing?.input_per_1m_usd),
    outputPer1M: num(m.pricing?.output_per_1m_usd),
    capabilities: {
      toolCalling: Boolean(m.capabilities?.tool_calling),
      vision: Boolean(m.capabilities?.vision),
      reasoning: Boolean(m.capabilities?.reasoning),
    },
  }))
  .filter((m) => m.id && m.inputPer1M !== null && m.outputPer1M !== null)

const featuredRank = (id) => {
  const i = FEATURED.indexOf(id)
  return i === -1 ? Number.MAX_SAFE_INTEGER : i
}

const sorted = [...models].sort((a, b) => {
  const fa = featuredRank(a.id)
  const fb = featuredRank(b.id)
  if (fa !== fb) return fa - fb
  if (a.provider !== b.provider) return a.provider.localeCompare(b.provider)
  if (a.inputPer1M !== b.inputPer1M) return a.inputPer1M - b.inputPer1M
  return a.id.localeCompare(b.id)
})

// Cheapest chat-capable models, ranked by a weighted typical turn:
// ~2k input tokens + ~700 output tokens.
const turnCost = (m) => (2000 * m.inputPer1M + 700 * m.outputPer1M) / 1_000_000
const cheap = models
  .filter((m) => m.inputPer1M <= CHEAP_MAX_INPUT_PER_1M && m.outputPer1M <= CHEAP_MAX_OUTPUT_PER_1M)
  .sort((a, b) => turnCost(a) - turnCost(b))

const fmt = (n) => (n === null ? 'null' : String(n))

const lines = []
lines.push('// AUTO-GENERATED by scripts/sync-models.mjs — do not edit by hand.')
lines.push(`// Source: ${ENDPOINT}`)
lines.push(`// Synced: ${new Date().toISOString()}`)
lines.push('')
lines.push('export interface ApisRouterModel {')
lines.push('  id: string')
lines.push('  name: string')
lines.push('  provider: string')
lines.push('  contextLength: number | null')
lines.push('  maxCompletionTokens: number | null')
lines.push('  /** USD per 1M input tokens */')
lines.push('  inputPer1M: number | null')
lines.push('  /** USD per 1M output tokens */')
lines.push('  outputPer1M: number | null')
lines.push('  /** Estimated USD for one typical turn (~2k input + ~700 output tokens) */')
lines.push('  estimatedTurnCostUsd: number | null')
lines.push('  capabilities: { toolCalling: boolean; vision: boolean; reasoning: boolean }')
lines.push('}')
lines.push('')
lines.push('export const APISROUTER_MODELS: ApisRouterModel[] = [')
for (const m of sorted) {
  lines.push(
    `  { id: ${JSON.stringify(m.id)}, name: ${JSON.stringify(m.name)}, provider: ${JSON.stringify(m.provider)}, ` +
      `contextLength: ${fmt(m.contextLength)}, maxCompletionTokens: ${fmt(m.maxCompletionTokens)}, ` +
      `inputPer1M: ${fmt(m.inputPer1M)}, outputPer1M: ${fmt(m.outputPer1M)}, ` +
      `estimatedTurnCostUsd: ${turnCost(m).toFixed(6)}, ` +
      `capabilities: { toolCalling: ${m.capabilities.toolCalling}, vision: ${m.capabilities.vision}, reasoning: ${m.capabilities.reasoning} } },`,
  )
}
lines.push(']')
lines.push('')
lines.push('/** Every model id, in picker order (featured first). */')
lines.push('export const APISROUTER_MODEL_IDS: string[] = APISROUTER_MODELS.map((m) => m.id)')
lines.push('')
lines.push('/** All models, cheapest typical turn first. */')
lines.push('export const APISROUTER_MODELS_BY_PRICE: ApisRouterModel[] = [...APISROUTER_MODELS].sort(')
lines.push('  (a, b) =>')
lines.push('    (a.estimatedTurnCostUsd ?? Number.POSITIVE_INFINITY) - (b.estimatedTurnCostUsd ?? Number.POSITIVE_INFINITY) ||')
lines.push('    (a.inputPer1M ?? Number.POSITIVE_INFINITY) - (b.inputPer1M ?? Number.POSITIVE_INFINITY) ||')
lines.push('    a.id.localeCompare(b.id),')
lines.push(')')
lines.push('')
lines.push('/** Every model id, cheapest first. */')
lines.push('export const APISROUTER_MODEL_IDS_BY_PRICE: string[] = APISROUTER_MODELS_BY_PRICE.map((m) => m.id)')
lines.push('')
lines.push('/** Cheapest chat-capable models, cheapest typical turn first. */')
lines.push('export const APISROUTER_CHEAP_MODEL_IDS: string[] = [')
for (const m of cheap) {
  lines.push(`  ${JSON.stringify(m.id)}, // $${turnCost(m).toFixed(5)} per ~2k in / 700 out turn`)
}
lines.push(']')
lines.push('')
lines.push('export const APISROUTER_MODEL_PRICING: Record<string, { input: number; output: number }> = {')
for (const m of sorted) {
  lines.push(`  ${JSON.stringify(m.id)}: { input: ${m.inputPer1M}, output: ${m.outputPer1M} },`)
}
lines.push('}')
lines.push('')

mkdirSync(path.dirname(OUT), { recursive: true })
writeFileSync(OUT, lines.join('\n'), 'utf8')

console.log(`[models] wrote ${sorted.length} models -> ${path.relative(ROOT, OUT)}`)
console.log('[models] cheapest chat models:')
for (const m of cheap.slice(0, 10)) {
  console.log(
    `  ${m.id.padEnd(34)} in=$${m.inputPer1M.toFixed(3)}/1M out=$${m.outputPer1M.toFixed(3)}/1M  ≈$${turnCost(m).toFixed(5)}/turn`,
  )
}
