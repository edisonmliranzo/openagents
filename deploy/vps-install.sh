#!/usr/bin/env bash
# OpenAgents one-click VPS deploy
# Installs Docker, deploys the validated prod stack, and fronts it with Caddy TLS.
#
# Usage (on a fresh Ubuntu 22.04/24.04 box, as root or with sudo):
#   curl -fsSL <your-host>/openagents-vps-install.sh -o install.sh && bash install.sh you@example.com app.yourdomain.com
#
# Args:
#   $1 — your email (for Caddy / Let's Encrypt + owner bootstrap)
#   $2 — your domain (must already point at this server)
set -euo pipefail

EMAIL="${1:?Usage: install.sh <email> <domain>}"
DOMAIN="${2:?Usage: install.sh <email> <domain>}"
INSTALL_DIR="/opt/openagents"

echo "==> Installing prerequisites"
apt-get update -y
apt-get install -y ca-certificates curl git

if ! command -v docker >/dev/null 2>&1; then
  echo "==> Installing Docker"
  curl -fsSL https://get.docker.com | sh
fi

echo "==> Fetching OpenAgents"
mkdir -p "$INSTALL_DIR"
cd "$INSTALL_DIR"
if [ -d .git ]; then
  git pull --ff-only || true
else
  git clone https://github.com/edisonmliranzo/openagents.git .
fi

echo "==> Writing production env"
ENV_FILE="infra/docker/.env.prod"
SECRET=$(openssl rand -hex 32 2>/dev/null || head -c 32 /dev/urandom | xxd -p -c 64)
REFRESH_SECRET=$(openssl rand -hex 32 2>/dev/null || head -c 32 /dev/urandom | xxd -p -c 64)
ENC_KEY=$(openssl rand -hex 32 2>/dev/null || head -c 32 /dev/urandom | xxd -p -c 64)
PGPASS=$(openssl rand -hex 16 2>/dev/null || head -c 16 /dev/urandom | xxd -p -c 32)
WORKER=$(openssl rand -hex 24 2>/dev/null || head -c 24 /dev/urandom | xxd -p -c 48)

if [ ! -f "$ENV_FILE" ]; then
  cat > "$ENV_FILE" <<EOF
# OpenAgents production env (generated by vps-install.sh)
NODE_ENV=production
FRONTEND_URL=https://${DOMAIN}
NEXT_PUBLIC_API_URL=https://${DOMAIN}
OPENAGENTS_INTERNAL_API_URL=http://api:3001
WEB_HOST_PORT=3000
API_HOST_PORT=127.0.0.1:3001
POSTGRES_HOST_PORT=127.0.0.1:5432
REDIS_HOST_PORT=127.0.0.1:6379
POSTGRES_DB=openagents
POSTGRES_USER=postgres
POSTGRES_PASSWORD=${PGPASS}
DATABASE_URL=postgresql://postgres:${PGPASS}@postgres:5432/openagents
REDIS_URL=redis://redis:6379
PORT=3001
API_PORT=3001
JWT_SECRET=${SECRET}
JWT_EXPIRES_IN=15m
JWT_REFRESH_SECRET=${REFRESH_SECRET}
JWT_REFRESH_EXPIRES_IN=7d
ENCRYPTION_KEY=${ENC_KEY}
CREATOR_EMAIL=${EMAIL}
CREATOR_EMAILS=${EMAIL}
DEFAULT_LLM_PROVIDER=ollama
OLLAMA_BASE_URL=http://host.docker.internal:11434
OLLAMA_ALLOWED_HOSTS=localhost,127.0.0.1,::1,host.docker.internal
TOOL_RUN_WORKER_TOKEN=${WORKER}
APPROVAL_WORKER_TOKEN=${WORKER}
EOF
  echo "    wrote $ENV_FILE (secrets generated)"
fi

echo "==> Building and starting the stack (this takes a few minutes)"
node scripts/prod-stack.mjs build
WEB_HOST_PORT=3000 node scripts/prod-stack.mjs up

echo "==> Installing Caddy for automatic HTTPS"
apt-get install -y debian-keyring debian-archive-keyring apt-transport-https
curl -1sLf 'https://dl.cloudflare.com/cloudflare-main.gpg' 2>/dev/null | true
curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' | gpg --batch --yes --dearmor -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg 2>/dev/null || true
curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' | tee /etc/apt/sources.list.d/caddy-stable.list >/dev/null
apt-get update -y && apt-get install -y caddy

cat > /etc/caddy/Caddyfile <<EOF
${DOMAIN} {
  encode gzip
  reverse_proxy 127.0.0.1:3000
  header Strict-Transport-Security "max-age=31536000; includeSubDomains"
}
EOF
systemctl enable --now caddy
systemctl reload caddy || true

echo ""
echo "============================================================"
echo "  OpenAgents is live: https://${DOMAIN}"
echo ""
echo "  1. Open the URL and register with ${EMAIL} (owner account)."
echo "  2. Connect an LLM provider in Settings (Ollama or a cloud key)."
echo "  3. Point your phone at the same URL — it installs as a PWA."
echo ""
echo "  Stack managed with: node scripts/prod-stack.mjs {ps,logs,down}"
echo "============================================================"
